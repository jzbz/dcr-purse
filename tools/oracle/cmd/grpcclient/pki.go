// The certificates are made with crypto/x509 and the parameters of the code
// that makes them in dcrwallet, since dcrd's certgen module is in dcrwallet's
// module graph but not in this module's go.sum:
//
//   - the server pair follows certgen v1.2.0 (NewTLSCertPair and
//     NewEd25519TLSCertPair, called from dcrwallet's generateRPCKeyPair):
//     organization "dcrwallet autogenerated cert", ten years, NotBefore one
//     day back, a serial below 2^128, KeyUsage KeyEncipherment |
//     DigitalSignature | CertSign, IsCA, an EC key as "EC PRIVATE KEY" (SEC
//     1) and an Ed25519 key as "PRIVATE KEY" (PKCS #8). certgen puts the
//     host name and every interface address in the certificate; here the
//     names are "localhost" and the addresses 127.0.0.1 and ::1 only, which
//     is all a loopback test dials;
//   - the client CA and client certificate follow dcrwallet's
//     --issueclientcert (generateAuthority, createSignedClientCert,
//     marshalPrivateKey in rpcserver.go), keys as "PRIVATE KEY" (PKCS #8);
//   - an RSA server key, which dcrwallet loads when a user supplies one but
//     never generates, is written as "RSA PRIVATE KEY" (PKCS #1).
//
// Files written into dir:
//
//	rpc.cert, rpc.key          the server pair
//	ca.pem                     dcrwallet's issued client CA
//	client.pem, client.key     a client certificate the CA signed
//	clients.pem                the --clientcafile: ca.pem followed by the
//	                           two self-signed client certificates below
//	selfsigned.pem, .key       a self-signed client certificate without
//	                           basic constraints (a leaf that is its own
//	                           trust anchor, listed in clients.pem)
//	selfsigned-ca.pem, .key    a self-signed client certificate made with
//	                           certgen's template (IsCA, CertSign), also
//	                           listed in clients.pem
//	wrongca-client.pem, .key   a client certificate from another CA of the
//	                           same template, not in clients.pem
//	expired-client.pem, .key   a client certificate the right CA signed,
//	                           valid from two days ago until one day ago

type pkiArgs struct {
	Dir       string `json:"dir"`
	ServerKey string `json:"server_key"`
	ClientKey string `json:"client_key"`
}

// endOfTime is the end of ASN.1 time, as certgen and rpcserver.go clamp to.
var endOfTime = time.Date(2049, 12, 31, 23, 59, 59, 0, time.UTC)

func cmdPKI(raw json.RawMessage) (any, error) {
	var a pkiArgs
	if err := json.Unmarshal(raw, &a); err != nil {
		return nil, err
	}
	if a.ServerKey == "" {
		a.ServerKey = "Ed25519"
	}
	if a.ClientKey == "" {
		a.ClientKey = "Ed25519"
	}
	if err := os.MkdirAll(a.Dir, 0o700); err != nil {
		return nil, err
	}
	files := map[string]string{}
	write := func(name string, data []byte) error {
		p := filepath.Join(a.Dir, name)
		files[name] = p
		return os.WriteFile(p, data, 0o600)
	}

	// Server pair (certgen's template).
	certPEM, keyPEM, err := serverPair(a.ServerKey)
	if err != nil {
		return nil, err
	}
	if err := write("rpc.cert", certPEM); err != nil {
		return nil, err
	}
	if err := write("rpc.key", keyPEM); err != nil {
		return nil, err
	}

	now := time.Now()
	validUntil := now.Add(10 * 365 * 24 * time.Hour)
	if validUntil.After(endOfTime) {
		validUntil = endOfTime
	}

	// The issued client CA and its client certificate.
	ca, caKey, caPEM, err := authority(a.ClientKey, now, validUntil)
	if err != nil {
		return nil, err
	}
	if err := write("ca.pem", caPEM); err != nil {
		return nil, err
	}
	clientPEM, clientKey, err := signedClient(a.ClientKey, ca, caKey, now.Add(-24*time.Hour), ca.NotAfter)
	if err != nil {
		return nil, err
	}
	if err := write("client.pem", clientPEM); err != nil {
		return nil, err
	}
	if err := write("client.key", clientKey); err != nil {
		return nil, err
	}

	// An expired client certificate from the same CA.
	expPEM, expKey, err := signedClient(a.ClientKey, ca, caKey, now.Add(-48*time.Hour), now.Add(-24*time.Hour))
	if err != nil {
		return nil, err
	}
	if err := write("expired-client.pem", expPEM); err != nil {
		return nil, err
	}
	if err := write("expired-client.key", expKey); err != nil {
		return nil, err
	}

	// A client certificate from a CA the server does not trust.
	wrongCA, wrongKey, _, err := authority(a.ClientKey, now, validUntil)
	if err != nil {
		return nil, err
	}
	wPEM, wKey, err := signedClient(a.ClientKey, wrongCA, wrongKey, now.Add(-24*time.Hour), wrongCA.NotAfter)
	if err != nil {
		return nil, err
	}
	if err := write("wrongca-client.pem", wPEM); err != nil {
		return nil, err
	}
	if err := write("wrongca-client.key", wKey); err != nil {
		return nil, err
	}

	// Self-signed client certificates listed in clients.pem.
	ssPEM, ssKey, err := selfSignedClient(a.ClientKey, false, now, validUntil)
	if err != nil {
		return nil, err
	}
	if err := write("selfsigned.pem", ssPEM); err != nil {
		return nil, err
	}
	if err := write("selfsigned.key", ssKey); err != nil {
		return nil, err
	}
	sscPEM, sscKey, err := selfSignedClient(a.ClientKey, true, now, validUntil)
	if err != nil {
		return nil, err
	}
	if err := write("selfsigned-ca.pem", sscPEM); err != nil {
		return nil, err
	}
	if err := write("selfsigned-ca.key", sscKey); err != nil {
		return nil, err
	}

	clients := bytes.Join([][]byte{caPEM, ssPEM, sscPEM}, nil)
	if err := write("clients.pem", clients); err != nil {
		return nil, err
	}
	return files, nil
}

func generateKey(kind string) (crypto.PublicKey, crypto.Signer, error) {
	switch kind {
	case "Ed25519":
		seed := make([]byte, ed25519.SeedSize)
		if _, err := rand.Read(seed); err != nil {
			return nil, nil, err
		}
		k := ed25519.NewKeyFromSeed(seed)
		return k.Public(), k, nil
	case "P-256", "P-384", "P-521":
		curve := map[string]elliptic.Curve{
			"P-256": elliptic.P256(), "P-384": elliptic.P384(), "P-521": elliptic.P521(),
		}[kind]
		k, err := ecdsa.GenerateKey(curve, rand.Reader)
		if err != nil {
			return nil, nil, err
		}
		return k.Public(), k, nil
	case "RSA-2048":
		k, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			return nil, nil, err
		}
		return k.Public(), k, nil
	}
	return nil, nil, fmt.Errorf("unknown key type %q", kind)
}

func serial() *big.Int {
	limit := new(big.Int).Lsh(big.NewInt(1), 128)
	n, err := rand.Int(rand.Reader, limit)
	if err != nil {
		panic(err)
	}
	return n
}

func pemBlock(typ string, der []byte) []byte {
	return pem.EncodeToMemory(&pem.Block{Type: typ, Bytes: der})
}

func pkcs8(key crypto.Signer) ([]byte, error) {
	der, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, err
	}
	return pemBlock("PRIVATE KEY", der), nil
}

func serverPair(kind string) (certPEM, keyPEM []byte, err error) {
	pub, priv, err := generateKey(kind)
	if err != nil {
		return nil, nil, err
	}
	now := time.Now()
	validUntil := now.Add(10 * 365 * 24 * time.Hour)
	if validUntil.After(endOfTime) {
		validUntil = endOfTime
	}
	template := x509.Certificate{
		SerialNumber: serial(),
		Subject: pkix.Name{
			Organization: []string{"dcrwallet autogenerated cert"},
			CommonName:   "localhost",
		},
		NotBefore: now.Add(-24 * time.Hour),
		NotAfter:  validUntil,
		KeyUsage: x509.KeyUsageKeyEncipherment | x509.KeyUsageDigitalSignature |
			x509.KeyUsageCertSign,
		IsCA:                  true,
		BasicConstraintsValid: true,
		DNSNames:              []string{"localhost"},
		IPAddresses:           []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("::1")},
	}
	der, err := x509.CreateCertificate(rand.Reader, &template, &template, pub, priv)
	if err != nil {
		return nil, nil, err
	}
	switch k := priv.(type) {
	case *ecdsa.PrivateKey:
		b, err := x509.MarshalECPrivateKey(k)
		if err != nil {
			return nil, nil, err
		}
		keyPEM = pemBlock("EC PRIVATE KEY", b)
	case *rsa.PrivateKey:
		keyPEM = pemBlock("RSA PRIVATE KEY", x509.MarshalPKCS1PrivateKey(k))
	default:
		keyPEM, err = pkcs8(priv)
		if err != nil {
			return nil, nil, err
		}
	}
	return pemBlock("CERTIFICATE", der), keyPEM, nil
}

func authority(kind string, now, validUntil time.Time) (*x509.Certificate, crypto.Signer, []byte, error) {
	pub, priv, err := generateKey(kind)
	if err != nil {
		return nil, nil, nil, err
	}
	template := &x509.Certificate{
		SerialNumber: serial(),
		Subject: pkix.Name{
			CommonName:         "dcrwallet",
			Organization:       []string{"dcrwallet"},
			OrganizationalUnit: []string{"dcrwallet certificate authority"},
		},
		NotBefore:             now.Add(-24 * time.Hour),
		NotAfter:              validUntil,
		KeyUsage:              x509.KeyUsageCertSign,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, pub, priv)
	if err != nil {
		return nil, nil, nil, err
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, nil, nil, err
	}
	return cert, priv, pemBlock("CERTIFICATE", der), nil
}

func signedClient(kind string, ca *x509.Certificate, caKey crypto.Signer, notBefore, notAfter time.Time) (certPEM, keyPEM []byte, err error) {
	pub, priv, err := generateKey(kind)
	if err != nil {
		return nil, nil, err
	}
	template := &x509.Certificate{
		SerialNumber: serial(),
		NotBefore:    notBefore,
		NotAfter:     notAfter,
		Subject: pkix.Name{
			CommonName:         "dcrwallet",
			Organization:       []string{"dcrwallet"},
			OrganizationalUnit: []string{"dcrwallet client certificate"},
		},
	}
	der, err := x509.CreateCertificate(rand.Reader, template, ca, pub, caKey)
	if err != nil {
		return nil, nil, err
	}
	keyPEM, err = pkcs8(priv)
	if err != nil {
		return nil, nil, err
	}
	return pemBlock("CERTIFICATE", der), keyPEM, nil
}

func selfSignedClient(kind string, isCA bool, now, validUntil time.Time) (certPEM, keyPEM []byte, err error) {
	pub, priv, err := generateKey(kind)
	if err != nil {
		return nil, nil, err
	}
	template := &x509.Certificate{
		SerialNumber: serial(),
		NotBefore:    now.Add(-24 * time.Hour),
		NotAfter:     validUntil,
		Subject: pkix.Name{
			CommonName:   "client",
			Organization: []string{"self-signed client"},
		},
	}
	if isCA {
		template.KeyUsage = x509.KeyUsageKeyEncipherment | x509.KeyUsageDigitalSignature |
			x509.KeyUsageCertSign
		template.IsCA = true
		template.BasicConstraintsValid = true
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, pub, priv)
	if err != nil {
		return nil, nil, err
	}
	keyPEM, err = pkcs8(priv)
	if err != nil {
		return nil, nil, err
	}
	return pemBlock("CERTIFICATE", der), keyPEM, nil
}
