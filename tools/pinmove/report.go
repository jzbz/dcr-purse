// countsRow renders counts as table cells.
func countsRow(c Counts) string {
	return fmt.Sprintf("%d | %d | %d | %d | %d", c.Same, c.Shifted, c.Touched, c.Gone, c.Invalid)
}

func mdEscape(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

func revLine(r Rev) string {
	s := fmt.Sprintf("`%s` (%s", r.Commit[:12], r.Date)
	if r.Tags != "" {
		s += ", " + r.Tags
	}
	return s + ")"
}

// WriteReport writes the Markdown review list of ADR-0016 items 3 and 5.1.
func (a *Analysis) WriteReport(w io.Writer) error {
	p := func(format string, args ...any) { fmt.Fprintf(w, format, args...) }
	p("# Upstream range %s..%s\n\n", a.From.Short(), a.To.Short())
	p("Generated by `tools/pinmove report`. A report is a review list, not a parity claim.\n\n")
	if a.Empty() {
		p("**%s**\n\n", a.EmptyWarning())
	}
	p("- From: %s; to: %s.\n", revLine(a.From), revLine(a.To))
	plus, minus := 0, 0
	for _, c := range a.Commits {
		if c.Side == "+" {
			plus++
		} else {
			minus++
		}
	}
	p("- Commits: %d (%d reachable from the new revision only, %d from the old only; %d with a commit of the same subject on the other side).\n",
		len(a.Commits), plus, minus, len(a.Backports))
	var nGo, nDel, nAdd int
	paths := a.changedPaths()
	for _, f := range paths {
		fd := a.Files[f]
		if strings.HasSuffix(f, ".go") {
			nGo++
		}
		switch fd.Status {
		case 'D':
			nDel++
		case 'A':
			nAdd++
		}
	}
	p("- Files changed: %d (%d Go; %d added, %d deleted).\n", len(paths), nGo, nAdd, nDel)
	docs := a.Total(docGroups...)
	all, bare, amb := docs.Mapped, docs.BareRoot, docs.Ambiguous
	rw := a.Total(GroupRewrite).Mapped
	code := a.Total(GroupCode)
	p("- Upstream line citations (items), every document: %d same, %d shifted, %d touched, %d gone, %d invalid at the old revision. In the documents `cite` rewrites: %d same, %d shifted, %d touched, %d gone, %d invalid.\n",
		all.Same, all.Shifted, all.Touched, all.Gone, all.Invalid, rw.Same, rw.Shifted, rw.Touched, rw.Gone, rw.Invalid)
	p("- Bare-root citations (a bare file name at the upstream root; listed, never rewritten): %d same, %d shifted, %d touched, %d gone, %d invalid.\n",
		bare.Same, bare.Shifted, bare.Touched, bare.Gone, bare.Invalid)
	p("- Citations of a file that is both upstream and in this repository (`README.md:77`, `go.mod:3`; classified against the upstream file, listed, never rewritten): %d same, %d shifted, %d touched, %d gone, %d invalid.\n",
		amb.Same, amb.Shifted, amb.Touched, amb.Gone, amb.Invalid)
	p("- Items whose enclosing declaration differs at the new revision (listed, never rewritten): %d shifted, %d at unchanged numbers.\n",
		docs.DeclShifted, docs.DeclSame)
	cm := code.Mapped
	cm.Same += code.BareRoot.Same + code.Ambiguous.Same
	cm.Shifted += code.BareRoot.Shifted + code.Ambiguous.Shifted
	cm.Touched += code.BareRoot.Touched + code.Ambiguous.Touched
	cm.Gone += code.BareRoot.Gone + code.Ambiguous.Gone
	cm.Invalid += code.BareRoot.Invalid + code.Ambiguous.Invalid
	p("- Upstream line citations in code comments (%d Rust and Go files under `%s`, the oracle's copies of upstream source left out; listed, never rewritten): %d same, %d shifted, %d touched, %d gone, %d invalid; %d whose enclosing declaration differs.\n",
		len(a.Code), strings.Join(codeRoots, "`, `"), cm.Same, cm.Shifted, cm.Touched, cm.Gone, cm.Invalid, code.DeclShifted+code.DeclSame)
	unres := 0
	for i := range a.Results {
		if r := &a.Results[i]; r.Group != GroupCode && r.Target == TargetUnresolved && len(r.Items) > 0 {
			unres++
		}
	}
	p("- Line citations that resolve to no file, so that nothing here classifies them: %d (`pinmove survey` lists them).\n", unres)
	p("- go.mod: %d modules whose requirement or effective (replaced) version changes, %d replace directive changes.\n", len(a.ModChanges), len(a.Replaces))
	if b := a.Batteries; b != nil {
		vc := b.VerdictCounts()
		p("- Frozen files: %d to regenerate because something they depend on changed, %d pin-only, %d that do not move; %d oracle copies of upstream source to regenerate.\n",
			vc[VerdictRegenerate], vc[VerdictPinOnly], vc[VerdictUnchanged], b.CopiesChanged())
	} else {
		p("- Frozen files: not computed (no oracle module).\n")
	}
	p("\n")

	p("## Commits\n\n")
	if len(a.Commits) == 0 {
		p("None.\n\n")
	} else {
		p("| Side | Commit | Date | Subject | Files |\n|---|---|---|---|---|\n")
		for _, c := range a.Commits {
			subj := mdEscape(c.Subject)
			if h, ok := a.Backports[c.Hash]; ok {
				subj += fmt.Sprintf(" (same subject: `%s`)", h[:8])
			}
			if c.Merge {
				subj += " (merge)"
			}
			p("| %s | `%s` | %s | %s | %d |\n", c.Side, c.Hash[:8], c.Date, subj, len(c.Files))
		}
		p("\n")
	}

	p("## go.mod\n\n")
	if len(a.ModChanges) == 0 && len(a.Replaces) == 0 {
		p("No requirement or replace directive changed.\n\n")
	} else {
		for _, m := range a.ModChanges {
			ind := ""
			if m.Indirect {
				ind = " (indirect)"
			}
			p("- `%s`%s: %s\n", m.Module, ind, m)
		}
		for _, r := range a.Replaces {
			p("- replace %s\n", r)
		}
		p("\n")
	}
	if a.OldMod.Go != a.NewMod.Go {
		p("The `go` directive changes: %s -> %s.\n\n", orNone(a.OldMod.Go), orNone(a.NewMod.Go))
	}

	p("## Changed files\n\n")
	if len(paths) == 0 {
		p("None.\n\n")
	}
	for _, f := range paths {
		fd := a.Files[f]
		var hs []string
		for _, h := range fd.Hunks {
			hs = append(hs, h.String())
		}
		extra := ""
		if fd.Binary {
			extra = " binary"
		}
		if fd.Renamed != "" {
			extra += " (rename detection pairs it with `" + fd.Renamed + "`)"
		}
		if fd.TypeChange {
			extra += " (replaced by an object of another type)"
		}
		p("- `%s` (%c%s): %s\n", f, fd.Status, extra, strings.Join(hs, "; "))
	}
	if len(paths) > 0 {
		p("\n")
	}

	p("## Citations by document\n\n")
	p("Upstream citations cite maps (written in full, completed from a list, given a section's source file, declared by a directive, or a root Go file), by item. `cite` rewrites the shifted ones in the documents of group `rewrite`. Code comments are not in this table; they have a list of their own below.\n\n")
	p("| Document | Group | Same | Shifted | Touched | Gone | Invalid | Bare-root touched, shifted or gone | Unresolved line citations | Dependency citations that move | Upstream-and-local touched, shifted or gone | Declaration differs |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	sums := a.Summaries()
	for _, s := range sums {
		if s.Group == GroupCode {
			continue
		}
		if s.Mapped.Total() == 0 && s.BareRoot.Total() == 0 && s.Ambiguous.Total() == 0 && s.Unresolved == 0 && s.DepMoves == 0 {
			continue
		}
		p("| `%s` | %s | %s | %d | %d | %d | %d | %d |\n", s.Doc, s.Group, countsRow(s.Mapped),
			s.BareRoot.Shifted+s.BareRoot.Touched+s.BareRoot.Gone, s.Unresolved, s.DepMoves,
			s.Ambiguous.Shifted+s.Ambiguous.Touched+s.Ambiguous.Gone, s.DeclReview)
	}
	p("\n")

	inDocs := func(r *Result) bool { return r.Group != GroupCode }
	a.writeItems(w, "Touched citations (re-read each)", func(r *Result, m Mapping) bool { return inDocs(r) && r.Mapped() && m.Class == Touched })
	a.writeItems(w, "Gone citations (re-locate each)", func(r *Result, m Mapping) bool { return inDocs(r) && r.Mapped() && m.Class == Gone })
	a.writeItems(w, "Shifted citations whose enclosing declaration differs (cite does not rewrite them; re-locate each)", func(r *Result, m Mapping) bool {
		return inDocs(r) && r.Mapped() && m.Class == Shifted && m.Review != ""
	})
	a.writeItems(w, "Citations at unchanged numbers whose enclosing declaration differs (re-read each)", func(r *Result, m Mapping) bool {
		return inDocs(r) && r.Mapped() && m.Class == Same && m.Review != ""
	})
	a.writeItems(w, "Citations already wrong at the old revision", func(r *Result, m Mapping) bool {
		return inDocs(r) && r.Target != TargetAmbiguous && m.Class == Invalid
	})
	a.writeItems(w, "Bare-root citations the range shifts or touches (check which file each means)", func(r *Result, m Mapping) bool {
		return inDocs(r) && r.Target == TargetUpstream && !r.Mapped() && (movedClass(m) || m.Review != "")
	})
	a.writeItems(w, "Citations of a file both upstream and in this repository that the range shifts, touches or removes upstream (never rewritten; check which file each means, and re-read it if the upstream one)", func(r *Result, m Mapping) bool {
		return inDocs(r) && r.Target == TargetAmbiguous && (movedClass(m) || m.Review != "")
	})
	a.writeCodeItems(w)

	p("## Unresolved line citations naming a changed file's base name\n\n")
	changedBase := map[string]bool{}
	for _, f := range paths {
		changedBase[baseName(f)] = true
	}
	n := 0
	for i := range a.Results {
		r := &a.Results[i]
		if r.Group == GroupCode || r.Target != TargetUnresolved || len(r.Items) == 0 || r.Path == "" || !changedBase[baseName(r.Path)] {
			continue
		}
		n++
		p("- `%s:%d` `%s`%s\n", r.Doc, r.Line, mdEscape(r.Raw), hintText(r.Hints, a.Files))
	}
	if n == 0 {
		p("None.\n")
	}
	p("\n")

	p("## Dependency citations whose module moves\n\n")
	p("The module's effective version (its requirement, or the target of a replace directive) changes.\n\n")
	n = 0
	for i := range a.Results {
		r := &a.Results[i]
		if r.Group != GroupCode && r.Target == TargetDependency && r.DepStatus == DepMoves && len(r.Items) > 0 {
			n++
			oldV, _ := a.OldMod.Effective(r.DepModule)
			newV, _ := a.NewMod.Effective(r.DepModule)
			note := ""
			if r.Version != oldV {
				note = fmt.Sprintf(" (cites %s; the old revision builds %s)", r.Version, oldV)
			}
			p("- `%s:%d` `%s`: `%s` %s -> %s%s\n", r.Doc, r.Line, mdEscape(r.Raw), r.DepModule, oldV, orNone(newV), note)
		}
	}
	if n == 0 {
		p("None.\n")
	}
	p("\n")

	a.writeQuirks(w)

	a.WriteBatteries(w, a.Batteries, "##", false)

	a.writePinText(w)

	p("## Review list by document\n\n")
	p("Documents citing a file the range changes; `docs/UPSTREAM.md`, whose notes are dated and never revised, is left out.\n\n")
	n = 0
	for _, s := range sums {
		if len(s.Commits) == 0 || s.Group == GroupDated || s.Group == GroupCode {
			continue
		}
		n++
		p("- `%s` (%s): commits %s; files %s\n", s.Doc, s.Group, strings.Join(s.Commits, ", "), "`"+strings.Join(s.ChangedFiles, "`, `")+"`")
	}
	if n == 0 {
		p("None.\n")
	}
	return nil
}

func baseName(p string) string {
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[i+1:]
	}
	return p
}

func hintText(hints []string, files map[string]*FileDiff) string {
	var changed []string
	for _, h := range hints {
		if files[h] != nil {
			changed = append(changed, "`"+h+"`")
		}
	}
	if len(changed) == 0 {
		return ""
	}
	return "; changed upstream files of that name: " + strings.Join(changed, ", ")
}

func (a *Analysis) changedPaths() []string {
	paths := make([]string, 0, len(a.Files))
	for f := range a.Files {
		paths = append(paths, f)
	}
	sort.Strings(paths)
	return paths
}

func (a *Analysis) writeItems(w io.Writer, title string, keep func(*Result, Mapping) bool) {
	fmt.Fprintf(w, "## %s\n\n", title)
	n := 0
	for i := range a.Results {
		r := &a.Results[i]
		for j, m := range r.Maps {
			if !keep(r, m) {
				continue
			}
			n++
			it := r.Items[j]
			fmt.Fprintf(w, "- `%s:%d` `%s` item %s of `%s`", r.Doc, r.Line, mdEscape(r.Raw), itemText(it), r.Path)
			switch m.Class {
			case Touched:
				var hs []string
				for _, h := range m.Hunks {
					hs = append(hs, h.String())
				}
				if len(hs) > 0 {
					fmt.Fprintf(w, ": hunks %s", strings.Join(hs, "; "))
				} else {
					fmt.Fprintf(w, ": binary change")
				}
			case Gone:
				if m.TypeChange {
					fmt.Fprintf(w, ": file replaced by an object of another type (a symbolic link or a submodule)")
				} else if m.RenamedTo != "" {
					fmt.Fprintf(w, ": file deleted; rename detection pairs it with `%s`", m.RenamedTo)
				} else {
					fmt.Fprintf(w, ": file deleted")
				}
			case Invalid:
				fmt.Fprintf(w, ": the file has %d lines at the old revision", m.OldLineEnd)
			case Shifted:
				fmt.Fprintf(w, ": would become %s", itemText(Item{Start: m.NewStart, End: m.NewEnd}))
				if m.Review != "" {
					fmt.Fprintf(w, ", but %s", m.Review)
				}
			case Same:
				fmt.Fprintf(w, ": unchanged numbers")
				if m.Review != "" {
					fmt.Fprintf(w, ", but %s", m.Review)
				}
			}
			if r.Target == TargetAmbiguous {
				fmt.Fprintf(w, " (`%s` is also a file of this repository)", r.Path)
			}
			if r.Section != "" {
				fmt.Fprintf(w, " (section: %s)", mdEscape(r.Section))
			}
			fmt.Fprintln(w)
		}
	}
	if n == 0 {
		fmt.Fprintln(w, "None.")
	}
	fmt.Fprintln(w)
}

// movedClass reports whether a mapping is one a reviewer acts on: the
// numbers change, a line changed, or the file is gone.
func movedClass(m Mapping) bool {
	return m.Class == Shifted || m.Class == Touched || m.Class == Gone
}

// writeCodeItems lists the citations in code comments the range moves:
// ADR-0016 item 5.8 rewrites documents only, so every one of these is
// corrected by hand in the move.
func (a *Analysis) writeCodeItems(w io.Writer) {
	a.writeItems(w, "Citations in code comments the range shifts, touches or removes (never rewritten; correct each by hand)", func(r *Result, m Mapping) bool {
		return r.Group == GroupCode && (movedClass(m) || m.Class == Invalid || m.Review != "")
	})
}

// writeQuirks lists QUIRKS.md entries citing a changed upstream file.
func (a *Analysis) writeQuirks(w io.Writer) {
	fmt.Fprintf(w, "## QUIRKS entries citing changed files\n\n")
	type entry struct {
		files   map[string]bool
		classes Counts
	}
	entries := map[string]*entry{}
	var order []string
	for i := range a.Results {
		r := &a.Results[i]
		if r.Doc != "docs/QUIRKS.md" || a.Files[r.Path] == nil {
			continue
		}
		// A file both upstream and in this repository counts when it is
		// cited with a line ("README.md:77").
		if r.Target != TargetUpstream && !(r.Target == TargetAmbiguous && len(r.Items) > 0) {
			continue
		}
		id := r.Section
		if !strings.HasPrefix(id, "QK-") {
			continue
		}
		if f := strings.Fields(id); len(f) > 0 {
			id = f[0]
		}
		e := entries[id]
		if e == nil {
			e = &entry{files: map[string]bool{}}
			entries[id] = e
			order = append(order, id)
		}
		e.files[r.Path] = true
		for _, m := range r.Maps {
			e.classes.add(m.Class)
		}
	}
	if len(order) == 0 {
		fmt.Fprintln(w, "None.")
		fmt.Fprintln(w)
		return
	}
	for _, id := range order {
		e := entries[id]
		var fs []string
		for f := range e.files {
			fs = append(fs, "`"+f+"`")
		}
		sort.Strings(fs)
		fmt.Fprintf(w, "- %s: %s (items: %d same, %d shifted, %d touched, %d gone)\n", id, strings.Join(fs, ", "),
			e.classes.Same, e.classes.Shifted, e.classes.Touched, e.classes.Gone)
	}
	fmt.Fprintln(w)
}

// PinLines lists, per document outside docs/adr/ and docs/UPSTREAM.md,
// the lines that name the old revision's eight-digit abbreviation: the
// text a move updates by hand (ADR-0016, item 5.12).
func (a *Analysis) PinLines() map[string][]int {
	out := map[string][]int{}
	short := []byte(a.From.Short())
	for _, d := range a.Docs {
		if g := docGroup(d); g == GroupADR || g == GroupDated {
			continue
		}
		data, err := os.ReadFile(filepath.Join(a.Repo, filepath.FromSlash(d)))
		if err != nil {
			continue
		}
		for i, line := range bytes.Split(data, []byte("\n")) {
			if bytes.Contains(line, short) && !citedMarkerRe.Match(line) {
				out[d] = append(out[d], i+1)
			}
		}
	}
	return out
}

func (a *Analysis) writePinText(w io.Writer) {
	fmt.Fprintf(w, "## Text naming the old revision\n\n")
	fmt.Fprintf(w, "Lines that name `%s` outside `docs/adr/` and `docs/UPSTREAM.md` (item 5.12); `cite` rewrites none of them, and the move also extends the paragraph of `docs/adr/README.md` that names the pins and the dates each was in force. The code that names the pin (`DCRWALLET_PARITY_COMMIT`, the oracle's `go.mod`, `go.sum` and `dcrwallet.go.mod`) is item 5.3.\n\n", a.From.Short())
	pl := a.PinLines()
	n := 0
	for _, d := range a.Docs {
		ls := pl[d]
		if len(ls) == 0 {
			continue
		}
		n++
		var xs []string
		for _, l := range ls {
			xs = append(xs, fmt.Sprint(l))
		}
		fmt.Fprintf(w, "- `%s`: lines %s\n", d, strings.Join(xs, ", "))
	}
	if n == 0 {
		fmt.Fprintln(w, "None.")
	}
	fmt.Fprintln(w)
}

// jsonReport is the machine-readable report.
type jsonReport struct {
	From       Rev               `json:"from"`
	To         Rev               `json:"to"`
	Commits    []LogEntry        `json:"commits"`
	Backports  map[string]string `json:"sameSubject"`
	Files      []*FileDiff       `json:"files"`
	ModChanges []ModChange       `json:"goModChanges"`
	Replaces   []string          `json:"goModReplaces"`
	Totals     map[string]Totals `json:"totals"`
	Documents  []DocSummary      `json:"documents"`
	Citations  []Result          `json:"citations"`
	Unparsed   []Unparsed        `json:"unparsed"`
	Batteries  *Batteries        `json:"batteries,omitempty"`
	PinLines   map[string][]int  `json:"pinLines"`
}

// WriteJSON writes every citation with its classification.
func (a *Analysis) WriteJSON(w io.Writer) error {
	files := make([]*FileDiff, 0, len(a.Files))
	for _, p := range a.changedPaths() {
		files = append(files, a.Files[p])
	}
	var cites []Result
	for i := range a.Results {
		if len(a.Results[i].Items) > 0 {
			cites = append(cites, a.Results[i])
		}
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", " ")
	return enc.Encode(jsonReport{
		From: a.From, To: a.To, Commits: a.Commits, Backports: a.Backports, Files: files,
		ModChanges: a.ModChanges, Replaces: a.Replaces,
		Totals: map[string]Totals{"documents": a.Total(docGroups...), "rewriteGroup": a.Total(GroupRewrite),
			"code": a.Total(GroupCode)},
		Documents: a.Summaries(), Citations: cites, Unparsed: a.Unparsed, Batteries: a.Batteries,
		PinLines: a.PinLines(),
	})
}

// WriteBatteriesReport writes the batteries command's Markdown report.
func (a *Analysis) WriteBatteriesReport(w io.Writer) error {
	fmt.Fprintf(w, "# Frozen files at %s", a.From.Short())
	if a.To.Commit != a.From.Commit {
		fmt.Fprintf(w, " for a move to %s", a.To.Short())
	}
	fmt.Fprintf(w, "\n\nGenerated by `tools/pinmove batteries`.\n\n- From: %s; to: %s.\n", revLine(a.From), revLine(a.To))
	fmt.Fprintf(w, "- Upstream files changed: %d; go.mod modules whose requirement or effective version changes: %d.\n\n", len(a.Files), len(a.ModChanges))
	a.WriteBatteries(w, a.Batteries, "##", true)
	return nil
}

// WriteBatteriesJSON writes the batteries analysis as JSON.
func (a *Analysis) WriteBatteriesJSON(w io.Writer) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", " ")
	return enc.Encode(struct {
		From      Rev        `json:"from"`
		To        Rev        `json:"to"`
		Batteries *Batteries `json:"batteries"`
	}{a.From, a.To, a.Batteries})
}
